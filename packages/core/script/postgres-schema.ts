import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("..", import.meta.url))
const target = path.join(root, "src/database/postgres/baseline.ts")
const temporary = await mkdtemp(path.join(tmpdir(), "omai-postgres-schema-"))
try {
  const config = path.join(temporary, "drizzle.config.ts")
  await writeFile(
    config,
    `export default ${JSON.stringify({
      dialect: "postgresql",
      schema: [path.join(root, "src/**/*.sql.ts"), path.join(root, "src/**/sql.ts")],
      out: path.join(temporary, "generated"),
    })}`,
  )
  const child = Bun.spawn([process.execPath, "drizzle-kit", "generate", "--config", config], {
    cwd: root,
    env: { ...process.env, OPENCODE_DATABASE_SCHEMA: "opencode" },
    stdout: "pipe",
    stderr: "pipe",
  })
  const [code, stdout, stderr] = await Promise.all([
    child.exited,
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
  ])
  if (code !== 0) throw new Error(`PostgreSQL schema generation failed:\n${stdout}\n${stderr}`)
  const files = await Array.fromAsync(
    new Bun.Glob("*/migration.sql").scan({ cwd: path.join(temporary, "generated"), absolute: true }),
  )
  if (files.length !== 1) throw new Error("Expected exactly one generated PostgreSQL baseline")
  const sql = (await readFile(files[0], "utf8"))
    .split("--> statement-breakpoint")
    .map((statement) => statement.trim())
    .filter((statement) => statement && statement !== 'CREATE SCHEMA "opencode";')
    .join("\n--> statement-breakpoint\n")
    .replaceAll('"opencode"', '"__OPENCODE_SCHEMA__"')
  const escaped = sql.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${")
  const content = `// Generated by script/postgres-schema.ts. Never change a deployed migration; append a new migration instead.\nexport const baseline = \`${escaped}\`\n`
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== content)
      throw new Error(
        "PostgreSQL baseline differs from the table declarations. Regenerate it before the initial release; use an incremental migration after deployment.",
      )
    console.log("PostgreSQL schema baseline is current")
  } else {
    await writeFile(target, content)
    console.log("Generated PostgreSQL baseline")
  }
} finally {
  await rm(temporary, { recursive: true, force: true })
}
